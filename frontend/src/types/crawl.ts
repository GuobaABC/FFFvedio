export function createEmptyCrawlConfig(): CrawlRunConfig {
  return {
    input: '',
    tags: [],
    note: '',
    maxUrls: 10,
    useLlm: true,
    textProviderId: '',
    respectRobots: true,
    intervalMs: 1500,
    timeoutS: 20,
  }
}

export function crawlStatusClass(status: string): string {
  switch (status) {
    case 'running':
      return 'ui-chip--running'
    case 'done':
      return 'ui-chip--ok'
    case 'failed':
      return 'ui-chip--error'
    case 'draft':
      return 'ui-chip--warn'
    default:
      return ''
  }
}

export function crawlStateClass(state: string): string {
  switch (state) {
    case 'STORED':
    case 'CACHED':
      return 'ui-chip--ok'
    case 'RULE_PROPOSED':
      return 'ui-chip--ok'
    case 'BLOCKED':
      return 'ui-chip--warn'
    case 'FAILED_RETRY':
      return 'ui-chip--error'
    default:
      return ''
  }
}

export function tierLabel(tier: string): string {
  if (!tier) {
    return '未抽取'
  }
  return CRAWL_TIER_LABELS[tier] ?? tier
}

export function formatConfidence(value: number): string {
  if (!value) {
    return '—'
  }
  return `${Math.round(value * 100)}%`
}

export function formatDuration(ms: number): string {
  if (!ms || ms <= 0) {
    return '—'
  }
  if (ms < 1000) {
    return `${Math.round(ms)}ms`
  }
  const seconds = ms / 1000
  if (seconds < 60) {
    return `${seconds.toFixed(1)}s`
  }
  return `${Math.floor(seconds / 60)}m${Math.round(seconds % 60)}s`
}

export function formatSecondsLabel(value: number): string {
  if (!value || value <= 0) {
    return ''
  }
  const total = Math.round(value)
  const minutes = Math.floor(total / 60)
  const seconds = total % 60
  return minutes > 0 ? `${minutes}:${String(seconds).padStart(2, '0')}` : `0:${String(seconds).padStart(2, '0')}`
}

/** 与 video.ts 的 formatClock 行为保持一致：把 RFC3339 渲染成 M-D HH:mm:ss */
export function formatCrawlClock(value: string): string {
  if (!value) {
    return '—'
  }
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) {
    return value
  }
  const pad = (input: number) => String(input).padStart(2, '0')
  return `${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(
    date.getMinutes(),
  )}:${pad(date.getSeconds())}`
}
