/**
 * 热点爬取模块的类型定义。
 * 与 Go 侧 crawl_models.go 的 json tag 一一对应，
 * 前端手写绑定（services/backend.ts）即可脱离 wailsjs 生成物独立编译。
 */

export type CrawlStatus = 'draft' | 'running' | 'done' | 'failed'

export type CrawlStage = 'INTAKE' | 'FETCH' | 'EXTRACT' | 'VALIDATE' | 'DONE'

export interface CrawlRunConfig {
  input: string
  tags: string[]
  note: string
  maxUrls: number
  useLlm: boolean
  textProviderId: string
  respectRobots: boolean
  intervalMs: number
  timeoutS: number
}

export interface CrawlThumbnail {
  url: string
  width: number
  height: number
  contentType: string
}

export interface CrawlItemOptional {
  author: string
  publishedAt: string
  durationSec: number
  tags: string[]
}

export interface CrawlItemMeta {
  extractedAt: string
  extractTier: string
  confidence: number
  httpStatus: number
  rendered: boolean
  latencyMs: number
  rawRef: string
  variants: string[]
  siteProfile: boolean
}

/** 抽取产物：标题 / 简介 / 封面 URL 三要素 + 可选元信息 */
export interface CrawlItem {
  id: string
  canonicalUrl: string
  originalUrl: string
  siteKey: string
  title: string
  description: string
  thumbnail: CrawlThumbnail
  optional: CrawlItemOptional
  meta: CrawlItemMeta
  createdAt: string
  updatedAt: string
}

export interface CrawlStep {
  step: string
  state: string
  tier: string
  status: string
  latencyMs: number
  note: string
  at: string
}

export interface CrawlResult {
  originalUrl: string
  canonicalUrl: string
  siteKey: string
  state: string
  tier: string
  httpStatus: number
  rendered: boolean
  confidence: number
  errorCode: string
  message: string
  latencyMs: number
  itemId: string
  cached: boolean
  steps: CrawlStep[]
}

export interface CrawlStats {
  total: number
  stored: number
  cached: number
  failed: number
  blocked: number
  llmCalls: number
  tierHits: Record<string, number>
  durationMs: number
}

export interface CrawlRunContext {
  results: CrawlResult[]
  items: CrawlItem[]
  stats: CrawlStats
  warnings: string[]
  logs: string[]
  lastRunAt: string
  finishedAt: string
}

export interface CrawlTask {
  id: string
  title: string
  stage: CrawlStage
  status: CrawlStatus
  error: string
  config: CrawlRunConfig
  run: CrawlRunContext
  createdAt: string
  updatedAt: string
}

export interface CrawlTaskInput {
  title: string
  config: CrawlRunConfig
}

export interface SiteCleaner {
  field: string
  regex: string
  replace: string
}

/** 站点画像：L4 规则沉淀，选择器 + 正则尾部清洗 + 命中统计 */
export interface SiteProfile {
  siteKey: string
  hostPattern: string
  requiresRender: boolean
  selectors: Record<string, string[]>
  cleaners: SiteCleaner[]
  hitSuccess: number
  hitFail: number
  lastVerifiedAt: string
  enabled: boolean
  autoGenerated: boolean
  reviewStatus: string
  updatedAt: string
}

export interface CrawlEnvironment {
  llmAvailable: boolean
  textModel: string
  browserSupport: boolean
  supportedSites: string[]
  notes: string[]
}

